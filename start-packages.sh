#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
RUN_DIR="$ROOT_DIR/.run"
PID_FILE="$RUN_DIR/packages.pids"
LOG_DIR="$RUN_DIR/logs"
ENV_FILE="$RUN_DIR/packages.env"

PACKAGES=(
  "es2vt"
  "es-api"
  "graphql-api"
)

mkdir -p "$RUN_DIR" "$LOG_DIR"

if [[ -f "$PID_FILE" ]]; then
  while IFS='|' read -r _ pid _; do
    if [[ -n "${pid:-}" ]] && kill -0 "$pid" 2>/dev/null; then
      echo "Existing running processes found in $PID_FILE. Stop them first with ./stop-packages.sh"
      exit 1
    fi
  done < "$PID_FILE"
fi

rm -f "$PID_FILE"

kill_port_if_busy() {
  local port="$1"
  local pids
  pids="$(lsof -tiTCP:"$port" -sTCP:LISTEN 2>/dev/null || true)"

  if [[ -z "$pids" ]]; then
    return
  fi

  while IFS= read -r pid; do
    if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
      kill "$pid"
      echo "Stopped existing process on port $port (PID $pid)"
    fi
  done <<< "$pids"
}

for port in 4000 4001 4002; do
  kill_port_if_busy "$port"
done

start_one() {
  local package_name="$1"
  local package_dir="$ROOT_DIR/packages/$package_name"
  local log_file="$LOG_DIR/$package_name.log"
  local run_script="start"

  if [[ ! -d "$package_dir" ]]; then
    echo "Missing package directory: $package_dir"
    exit 1
  fi

  if [[ "$package_name" == "graphql-api" ]]; then
    run_script="develop"
  fi

  (
    if [[ -s "$HOME/.nvm/nvm.sh" ]]; then
      # Ensure all package scripts run on the expected Node.js version.
      . "$HOME/.nvm/nvm.sh"
      nvm use v24.21.0 >/dev/null
    else
      echo "nvm not found at $HOME/.nvm/nvm.sh"
      exit 1
    fi
    cd "$package_dir"
    npm run "$run_script"
  ) >"$log_file" 2>&1 &

  local pid=$!
  printf '%s|%s|%s\n' "$package_name" "$pid" "$log_file" >> "$PID_FILE"
  echo "Started $package_name (PID $pid) -> $log_file"
}

for package in "${PACKAGES[@]}"; do
  start_one "$package"
done

cat >"$ENV_FILE" <<EOF
# Generated by start-packages.sh
# Source this file to load ports in your shell:
#   source .run/packages.env
EOF

get_port_for_pid() {
  local pid="$1"
  lsof -nP -a -p "$pid" -iTCP -sTCP:LISTEN 2>/dev/null \
    | awk 'NR>1 {print $9}' \
    | sed 's/.*://g' \
    | paste -sd ',' - \
    || true
}

for package in "${PACKAGES[@]}"; do
  pid="$(awk -F'|' -v p="$package" '$1 == p {print $2}' "$PID_FILE")"
  port=""

  for _ in {1..30}; do
    if [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null; then
      port="$(get_port_for_pid "$pid")"
      if [[ -n "$port" ]]; then
        break
      fi
    fi
    sleep 1
  done

  var_name="$(echo "$package" | tr '[:lower:]-' '[:upper:]_')_PORT"
  if [[ -n "$port" ]]; then
    printf 'export %s=%q\n' "$var_name" "$port" >> "$ENV_FILE"
    echo "$package port(s): $port"
  else
    printf '# %s port not detected yet\n' "$package" >> "$ENV_FILE"
    echo "$package port(s): not detected yet (check $LOG_DIR/$package.log)"
  fi
done

echo "All requested projects started."
echo "Port exports written to $ENV_FILE"
echo "Use ./stop-packages.sh to stop them."
